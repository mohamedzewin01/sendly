/// رسمة مبنية من حروف ورموز (ـ - * / \ + = ~ ^ % $ & وغيرها).
///
/// الحروف في واتساب بخط متناسب فتختل المحاذاة، لذلك تُكتب دائماً داخل كتلة
/// أحادية العرض (``` ... ```) فيأخذ كل حرف نفس العرض على كل الأجهزة.
class TextArt {
  const TextArt(this.name, this.lines);

  final String name;
  final List<String> lines;

  /// أقصى عرض بالحروف حتى لا يلتف السطر في الفقاعة (الالتفاف يكسر الرسمة)
  static const int maxWidth = 24;

  /// علامة اتجاه (LRM) في أول كل سطر: تجعل السطر من اليسار في أي فقاعة فلا تنعكس
  /// الأقواس والأسهم (< > ( ) / \\) في المحادثات العربية، وتحفظ الفراغات الأولى من القص.
  static const String _lineStart = '\u200E';

  int get width => lines.fold(0, (m, l) => l.length > m ? l.length : m);

  /// الرسمة كما تُعرض في المعاينة (بدون علامات الكتلة)
  String get plain => lines.join('\n');

  /// نص الرسالة: كتلة أحادية العرض تبدأ فوراً بعد ``` وتنتهي قبل ``` مباشرة
  String render() => '```${lines.map((l) => '$_lineStart$l').join('\n')}```';
}

