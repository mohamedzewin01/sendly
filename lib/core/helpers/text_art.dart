/// قالب «اسمك في شكل»: إطار أو زخرفة يُكتب الاسم في وسطها. كل حرف لاتيني بنفس العرض
/// فتتضبط الحواف تماماً. الحروف العربية بخط غير أحادي العرض، فلا يُرسم الحد الأيمن
/// لسطر الاسم وحده، وتبقى بقية الأسطر كاملة.
class NameArt {
  const NameArt(this.name, this.lines, {this.inner = 0, this.right = ''});

  final String name;

  /// أسطر القالب، والسطر الذي فيه {name} يُملأ بالاسم
  final List<String> lines;

  /// العرض الداخلي المخصص للاسم (0 = شريط حر بلا محاذاة)
  final int inner;

  /// الحد الأيمن الذي يُضاف بعد الاسم في الإطارات المغلقة (للأسماء اللاتينية فقط)
  final String right;

  static const String _slot = '{name}';
  static final RegExp _arabic = RegExp(r'[\u0600-\u06FF\u0750-\u077F]');

  static bool hasArabic(String text) => _arabic.hasMatch(text);

  /// ينظّف الاسم: بلا أسطر جديدة ولا علامات كتلة ولا علامات اتجاه ولا فراغات مكررة
  static String clean(String raw) => raw
      .replaceAll(RegExp(r'[\r\n`\u200E\u200F]'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();

  /// أقصى عدد حروف للاسم في هذا القالب
  int get maxLength => inner > 0 ? inner : 16;

  /// يبني الرسمة بالاسم المكتوب (أو «NAME» للمعاينة إن كان فارغاً)
  TextArt fill(String raw) {
    var text = clean(raw);
    if (text.isEmpty) text = 'NAME';
    if (text.length > maxLength) {
      text = text.substring(0, maxLength).trimRight();
    }
    final arabic = hasArabic(text);

    final out = <String>[];
    for (final line in lines) {
      if (!line.contains(_slot)) {
        out.add(line);
      } else if (inner == 0) {
        out.add(line.replaceFirst(_slot, text));
      } else if (right.isNotEmpty && !arabic) {
        // إطار مغلق: الاسم في المنتصف بعرض داخلي ثابت فتتضبط الحدود اليمنى
        final pad = inner - text.length;
        final left = pad ~/ 2;
        final centered = ' ' * left + text + ' ' * (pad - left);
        out.add(line.replaceFirst(_slot, centered) + right);
      } else {
        // إطار مفتوح (عربي) أو زخرفة بلا حد أيمن: إزاحة من اليسار فقط
        final left = (inner - text.length) ~/ 2;
        out.add(line.replaceFirst(_slot, ' ' * (left < 0 ? 0 : left) + text));
      }
    }
    return TextArt(name, out);
  }
}

