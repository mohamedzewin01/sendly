/// رسمة مبنية من شبكة رموز تعبيرية. كل خلية رمز واحد بنفس العرض، فيظهر الشكل
/// مضبوطاً في واتساب وغيره (على عكس الرسم بالمسافات والحروف الذي يختل مع الخط المتناسب).
///
/// كل صف نص من `#` و`.`: الأول يُرسم بالرمز المختار والثاني بالخلفية.
class EmojiArt {
  const EmojiArt(this.name, this.rows);

  final String name;
  final List<String> rows;

  int get width => rows.first.length;
  int get height => rows.length;

  /// علامة اتجاه (LRM) في أول كل سطر: تجعل السطر يُقرأ من اليسار في أي فقاعة،
  /// وتمنع واتساب من قصّ الفراغات الشفافة في بدايته فيبقى الشكل في مكانه.
  static const String _lineStart = '\u200E';

  /// يبني نص الرسمة: أسطر مفصولة بسطر جديد، ورمز (أو فراغ بعرض رمز) لكل خلية
  String render({required String fill, required String background}) {
    return rows
        .map(
          (row) =>
              _lineStart +
              [
                for (final cell in row.split(''))
                  cell == '#' ? fill : background,
              ].join(),
        )
        .join('\n');
  }
}

